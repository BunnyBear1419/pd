"""Stage 7 — configurable, rebrandable agency signage for the PDHQ blockout.

Run after Stage 2 (and preferably Stages 3–4) in the same Blender scene.
Change BRAND below to adapt the same architecture to police, FIB, sheriff,
federal, or private-security use. This creates editable Blender text and
simple sign backing meshes; it is not a final textured/signage asset pack.
"""
import bpy

PREFIX = "PDHQ_"

# ------------------------- BRAND CONFIGURATION -------------------------
BRAND = {
    "agency_name": "LOS SANTOS POLICE DEPARTMENT",
    "short_name": "LSPD",
    "subtitle": "HEADQUARTERS",
    "primary_color": (0.055, 0.12, 0.20, 1.0),
    "accent_color": (0.82, 0.66, 0.25, 1.0),
    "text_color": (0.96, 0.97, 0.98, 1.0),
    "show_subtitle": True,
}
# Example alternatives:
# FIB:      agency_name="FEDERAL INVESTIGATION BUREAU", short_name="FIB"
# Sheriff:  agency_name="LOS SANTOS COUNTY SHERIFF", short_name="LSCSO"
# Security: agency_name="PRIVATE SECURITY", short_name="SECURITY"

SIGN_COLLECTION = "PDHQ_BRANDING_SIGNS"
scene = bpy.context.scene

def get_collection(name):
    col = bpy.data.collections.get(name)
    if col is None:
        col = bpy.data.collections.new(name)
        scene.collection.children.link(col)
    return col

signs = get_collection(SIGN_COLLECTION)

# Remove only objects generated by this branding script, so reruns update
# signs cleanly without deleting building geometry or unrelated user objects.
for obj in list(signs.objects):
    bpy.data.objects.remove(obj, do_unlink=True)

def make_material(name, color, metallic=0.0, roughness=0.55):
    mat = bpy.data.materials.get(name) or bpy.data.materials.new(name)
    mat.diffuse_color = color
    mat.use_nodes = True
    bsdf = mat.node_tree.nodes.get("Principled BSDF")
    if bsdf:
        bsdf.inputs["Base Color"].default_value = color
        bsdf.inputs["Metallic"].default_value = metallic
        bsdf.inputs["Roughness"].default_value = roughness
    return mat

MAT_SIGN_BASE = make_material("MAT_Brand_Sign_Base", BRAND["primary_color"], 0.25)
MAT_ACCENT = make_material("MAT_Brand_Sign_Accent", BRAND["accent_color"], 0.35)
MAT_TEXT = make_material("MAT_Brand_Sign_Text", BRAND["text_color"], 0.05)

def move_to_signs(obj):
    for old in list(obj.users_collection):
        old.objects.unlink(obj)
    signs.objects.link(obj)
    return obj

def make_box(name, location, dimensions, material):
    bpy.ops.mesh.primitive_cube_add(size=1, location=location)
    obj = bpy.context.object
    obj.name = PREFIX + "BRAND_" + name
    obj.dimensions = dimensions
    bpy.ops.object.transform_apply(location=False, rotation=False, scale=True)
    obj.data.materials.append(material)
    return move_to_signs(obj)

def make_text(name, body, location, size, rotation, material, align_x="CENTER"):
    curve = bpy.data.curves.new(PREFIX + "BRAND_TEXT_" + name, type="FONT")
    curve.body = body
    curve.size = size
    curve.align_x = align_x
    curve.align_y = "CENTER"
    curve.extrude = 0.008
    curve.bevel_depth = 0.001
    obj = bpy.data.objects.new(PREFIX + "BRAND_TEXT_" + name, curve)
    signs.objects.link(obj)
    obj.location = location
    obj.rotation_euler = rotation
    obj.data.materials.append(material)
    return obj

def create_front_sign():
    # Front facade faces negative Y. Keep sign above the canopy, away from
    # the public entry opening. Dimensions are approximate blockout values.
    x, y, z = 0.0, -19.22, 5.55
    make_box("EXTERIOR_BACKPLATE", (x, y, z), (19.0, 0.28, 1.8), MAT_SIGN_BASE)
    make_box("EXTERIOR_ACCENT_STRIP", (x, y-0.16, z-0.68), (18.2, 0.05, 0.09), MAT_ACCENT)
    make_text("EXTERIOR_AGENCY", BRAND["agency_name"], (x, y-0.17, z+0.28),
              0.62, (1.57079632679, 0.0, 0.0), MAT_TEXT)
    make_text("EXTERIOR_SHORT_NAME", BRAND["short_name"], (x, y-0.18, z-0.35),
              0.42, (1.57079632679, 0.0, 0.0), MAT_ACCENT)

def create_lobby_plaque():
    # Interior-facing plaque near the public lobby entrance, also editable.
    x, y, z = 0.0, -17.8, 2.8
    make_box("LOBBY_PLAQUE_BACKPLATE", (x, y, z), (6.5, 0.12, 0.8), MAT_SIGN_BASE)
    make_text("LOBBY_PLAQUE", BRAND["short_name"] + "  |  " + BRAND["subtitle"],
              (x, y+0.075, z), 0.38, (-1.57079632679, 0.0, 0.0), MAT_TEXT)

create_front_sign()
if BRAND["show_subtitle"]:
    create_lobby_plaque()

print("Stage 7 branding signs generated for: " + BRAND["agency_name"])
print("Edit BRAND at the top of stage7/generate_stage7_branding.py and rerun to rebrand.")
